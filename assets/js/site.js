/* ═══════════════════════════════════════════════════ charts */
function palette() {
  const cs = getComputedStyle(document.documentElement);
  const g = (n) => cs.getPropertyValue(n).trim();
  return { text: g("--text-2"), grid: g("--line"),
           pal: [g("--accent"), g("--ok"), g("--warn"), g("--danger"), g("--accent-2")] };
}

function drawChart(el, spec) {
  if (!el || typeof Plotly === "undefined") return;
  const c = palette();
  const traces = (spec.series || []).map((s, i) => ({
    x: spec.x, y: s.y, name: s.name,
    type: spec.type === "line" ? "scatter" : "bar",
    mode: spec.type === "line" ? "lines+markers" : undefined,
    marker: { color: c.pal[i % c.pal.length] },
    line: { color: c.pal[i % c.pal.length], width: 2.4 },
  }));
  const shapes = [];
  if (spec.hline !== undefined && spec.hline !== null) {
    shapes.push({ type: "line", xref: "paper", x0: 0, x1: 1,
      y0: spec.hline, y1: spec.hline,
      line: { color: c.pal[3], width: 1.6, dash: "dash" } });
  }
  Plotly.newPlot(el, traces, {
    paper_bgcolor: "rgba(0,0,0,0)", plot_bgcolor: "rgba(0,0,0,0)",
    font: { color: c.text, size: 11,
            family: "ui-sans-serif, system-ui, sans-serif" },
    margin: { l: 58, r: 16, t: 10, b: 64 },
    xaxis: { gridcolor: c.grid, zerolinecolor: c.grid, automargin: true,
             tickangle: (spec.x || []).some((v) => String(v).length > 9) ? -22 : 0 },
    yaxis: { gridcolor: c.grid, zerolinecolor: c.grid, automargin: true,
             title: { text: spec.yaxis || "" },
             type: spec.log_y ? "log" : "linear" },
    shapes,
    showlegend: (spec.series || []).length > 1,
    legend: { orientation: "h", y: -0.26 },
  }, { displayModeBar: false, responsive: true });
  el._spec = spec;
}

function redrawChart(el) { if (el && el._spec) drawChart(el, el._spec); }

/* ═══════════════════════════════════════════════════ reveal */
function initReveal() {
  const els = $$(".reveal:not(.in)");
  if (!("IntersectionObserver" in window)) {
    els.forEach((e) => e.classList.add("in")); return;
  }
  const io = new IntersectionObserver((entries) => {
    entries.forEach((e, i) => {
      if (!e.isIntersecting) return;
      // small stagger so a grid animates in sequence rather than as a slab
      setTimeout(() => e.target.classList.add("in"), Math.min(i * 55, 330));
      io.unobserve(e.target);
    });
  }, { rootMargin: "0px 0px -8% 0px", threshold: 0.08 });
  els.forEach((e) => io.observe(e));
}

