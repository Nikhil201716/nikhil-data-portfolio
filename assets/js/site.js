/* ═══════════════════════════════════════════════════ boot */
async function boot() {
  initTheme();
  initNav();
  initTypewriter();

  try {
    const r = await fetch("data/catalog.json");
    state.catalog = await r.json();
  } catch (e) {
    console.error("catalog load failed", e);
    $("#projects-grid").innerHTML =
      '<p class="sec-sub">Catalog failed to load. Run build/build_catalog.py.</p>';
    return;
  }

  renderHeroStats();
  renderFindings();
  renderRoles();
  renderStack();
  renderFilters();
  renderProjects();
  renderBooks();
  stampBuild();
  initReveal();
  initModal();
}

/* ═══════════════════════════════════════════════════ chrome */
function initTheme() {
  const saved = localStorage.getItem("ns-theme") || "dark";
  document.documentElement.setAttribute("data-theme", saved);
  $("#theme").onclick = () => {
    const next = document.documentElement.getAttribute("data-theme") === "light"
      ? "dark" : "light";
    document.documentElement.setAttribute("data-theme", next);
    localStorage.setItem("ns-theme", next);
    // Plotly charts bake colours in at draw time, so any open chart must
    // be redrawn against the new palette rather than left mismatched.
    if (!$("#modal").hidden) $$(".m-chart").forEach(redrawChart);
  };
}

function initNav() {
  const nav = $("#nav");
  const onScroll = () => nav.classList.toggle("stuck", window.scrollY > 12);
  onScroll();
  window.addEventListener("scroll", onScroll, { passive: true });

  const toggle = $("#nav-toggle"), links = $("#nav-links");
  toggle.onclick = () => {
    const open = links.classList.toggle("open");
    toggle.setAttribute("aria-expanded", String(open));
  };
  $$("#nav-links a").forEach((a) => a.addEventListener("click", () => {
    links.classList.remove("open");
    toggle.setAttribute("aria-expanded", "false");
  }));
}

function initTypewriter() {
  const el = $("#hero-role");
  const roles = ["Data Engineer", "Analytics Engineer", "ML Engineer",
                 "AI Engineer", "QA / SDET"];
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    el.textContent = "Data & AI Engineer";
    el.style.setProperty("--cursor", "none");
    return;
  }
  let i = 0, j = 0, deleting = false;
  (function tick() {
    const word = roles[i];
    el.textContent = deleting ? word.slice(0, --j) : word.slice(0, ++j);
    let wait = deleting ? 40 : 78;
    if (!deleting && j === word.length) { deleting = true; wait = 1700; }
    else if (deleting && j === 0) { deleting = false; i = (i + 1) % roles.length; wait = 260; }
    setTimeout(tick, wait);
  })();
}

