function renderHeroStats() {
  const c = state.catalog;
  const repos = c.projects.filter((p) => p.exists !== false).length;
  const stats = [
    [c.n_projects ?? c.projects.length, "Projects built"],
    [c.n_metrics_extracted ?? 0, "Measured results"],
    [c.n_technologies ?? 0, "Technologies"],
    [c.n_topics ?? 0, "Topics covered"],
    [repos, "Public repos"],
  ];
  $("#hero-stats").innerHTML = stats.map(([v, k]) =>
    `<div class="hstat"><div class="hstat-v" data-count="${v}">0</div>
     <div class="hstat-k">${esc(k)}</div></div>`).join("");
  animateCounters();
}

function animateCounters() {
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  $$(".hstat-v").forEach((el) => {
    const target = Number(el.dataset.count) || 0;

    // The final value is written FIRST, unconditionally.
    //
    // requestAnimationFrame does not fire in a hidden or heavily throttled
    // tab, so a counter that only ever reaches its value inside a rAF loop
    // shows 0 to anyone who opens the page in a background tab - and to
    // any headless browser. Painting the real number first and animating
    // on top means the page is correct even when the animation never runs.
    el.textContent = target;
    if (reduce || target === 0) return;

    const dur = 1100, t0 = performance.now();
    let done = false;
    const finish = () => { if (!done) { done = true; el.textContent = target; } };

    (function step(now) {
      if (done) return;
      const k = Math.min((now - t0) / dur, 1);
      el.textContent = Math.round(target * (1 - Math.pow(1 - k, 3)));  // ease-out cubic
      if (k < 1) requestAnimationFrame(step); else finish();
    })(t0);

    // belt and braces: if rAF never resumes, land on the real value anyway
    setTimeout(finish, dur + 400);
  });
}

